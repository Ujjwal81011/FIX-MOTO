const express = require('express');
const { createPayment, markPaymentDone, myPayments, mechanicPayments, confirmPayment } = require('../controllers/paymentController');
const { protect, authorize } = require('../middleware/authMiddleware');
const router = express.Router();
router.use(protect);
router.post('/', authorize('customer'), createPayment);
router.get('/mine', authorize('customer'), myPayments);
router.patch('/:id/pay', authorize('customer'), markPaymentDone);
router.get('/mechanic', authorize('mechanic'), mechanicPayments);
router.patch('/:id/confirm', authorize('mechanic'), confirmPayment);
module.exports = router;
